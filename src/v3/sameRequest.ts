export const SAME_REQUEST_CRITERIA = `次の両方を満たすとき「同じ依頼」とみなす。
1. ユーザーが求めている行動(探す・調べる・教えてもらう・書いてもらう・操作してもらう・断られる種類の依頼をする、など)と、その対象の種類が同じ。
2. 片方への理想的な回答を、固有名詞・数字・順番・言い回しを入れ替えるだけで、もう片方への回答として使える。

次のどれかに当てはまるときは「同じ依頼」とみなさない。
- 分類や依頼の型(求人を探す、企業について調べる、など)が同じでも、依頼の中身(対象の職種・勤務地・働き方などの条件、知りたい項目)が違う。同じ分類の発話が似るのは避けられないので、中身まで同じものだけを挙げる。
- 同じ分類・同じ話題でも、求めている行動か、対象か、回答の中身を変える条件が違う(例: 「この求人の締め切りは?」と「この求人の交通費は?」、「献立を考えて」と「観葉植物を教えて」)。
- 片方にしかない条件や事情が、回答の中身を大きく変える。
直前の会話がある場合は、それも含めて依頼の中身を判断する。`;

